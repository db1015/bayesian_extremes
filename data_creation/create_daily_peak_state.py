#!/usr/bin/env python3
"""
Create the daily peak-state dataset used in the manuscript analyses.

This script processes hourly ERA5-derived input files over the Arabian
Peninsula and constructs the daily variables used by the downstream
ENSO/IOD and Bayesian extreme-value analyses. These include daily peak
wet-bulb temperature (Tw) and the atmospheric state concurrent with the
daily Tw maximum.

The hourly ``WetBulbTempInput`` files used as input were produced by an
upstream ERA5 preprocessing workflow and are not generated by this
script or distributed with this repository. Users wishing to reproduce
this step should provide equivalent hourly ERA5 fields containing
2-m air temperature, 2-m dewpoint temperature, and surface pressure.

Wet-bulb temperature is calculated from surface pressure, air
temperature, and specific humidity using the thermodynamic routines
included with this project.

Outputs
-------
Monthly NetCDF files containing daily peak-state variables over the
Arabian Peninsula study domain (10–34°N, 34–60°E).

These files provide the primary daily atmospheric inputs used by the
subsequent manuscript analyses.
"""

