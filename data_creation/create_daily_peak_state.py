# AP bounding box
LAT_MAX = 34
LAT_MIN = 10
LON_MIN = 34
LON_MAX = 60

# Chunking
CHUNKS = {"time": 24, "latitude": 80, "longitude": 80}

os.makedirs(OUT_DIR, exist_ok=True)

